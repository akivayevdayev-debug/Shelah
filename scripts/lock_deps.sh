#!/usr/bin/env bash
# Regenerate every Python lock file from the pins, in one go (npm run deps:lock).
#
#   scripts/lock_deps.sh            keep locked versions where the pins allow
#   scripts/lock_deps.sh --upgrade  also move unpinned (transitive) packages
#                                   to their newest versions
#
# Edit pins first: requirements.txt (and the same pins in pyproject.toml's
# [project].dependencies, which is what Vercel installs; the
# test_api_index_entrypoint tests fail on drift) and requirements-dev.txt.
# Then this rebuilds, for Linux x86_64 and Python 3.14 like Vercel and CI:
#   requirements.lock.txt      hash-locked production set (CI, pip-audit)
#   requirements-dev.lock.txt  hash-locked dev/CI set, constrained by the above
#   uv.lock                    what the Vercel build installs from
# The hand-written preamble above "# This file was autogenerated" in each
# .lock.txt file is kept.
#
# Plain bash 3 (macOS /bin/bash).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

UPGRADE=()
[ "${1:-}" = "--upgrade" ] && UPGRADE=(--upgrade)
TARGET=(--python-platform x86_64-manylinux2014 --python-version 3.14)

compile_keeping_preamble() {
  local out="$1"; shift
  local preamble
  preamble="$(mktemp)"
  awk '/^# This file was autogenerated/{exit} {print}' "$out" > "$preamble"
  uv pip compile "$@" --generate-hashes "${TARGET[@]}" ${UPGRADE[@]+"${UPGRADE[@]}"} -o "$out" --quiet
  cat "$preamble" "$out" > "$out.tmp" && mv "$out.tmp" "$out"
  rm -f "$preamble"
}

echo "== requirements.lock.txt"
compile_keeping_preamble requirements.lock.txt requirements.txt
echo "== requirements-dev.lock.txt"
compile_keeping_preamble requirements-dev.lock.txt requirements-dev.txt --constraint requirements.lock.txt
echo "== uv.lock"
uv lock ${UPGRADE[@]+"${UPGRADE[@]}"} --quiet

echo
git --no-pager diff --stat -- requirements.lock.txt requirements-dev.lock.txt uv.lock
echo "Next: install the new versions locally (uv pip install --python .venv/bin/python -r requirements.txt -r requirements-dev.txt), then npm run finish."
