#!/usr/bin/env node
/**
 * Builds static/min/: the minified stylesheet bundle, the minified classic
 * scripts and the bundled ES modules the pages ship.
 *
 *   npm run build:assets          write static/min/
 *   npm run build:assets -- --check   exit 1 if static/min/ is not what the
 *                                     sources build to (CI runs this)
 *
 * The output is committed, like static/css/tailwind.css: Vercel serves the
 * repository's files and runs no build, and backend/module_versions.py
 * serves static/min/ only while the manifest still describes the sources on
 * disk (an edit to static/css/*.css or static/js/*.js makes the page fall back
 * to the originals until this is run again). Nothing here changes what the
 * code does -- only whitespace, names and the number of requests:
 *
 *   css/app.css        every page stylesheet, concatenated in the order
 *                      templates/index.html linked them (the cascade is the
 *                      order, so it is kept) and minified.
 *   js/<name>.js       each classic script (no import/export) minified on its
 *                      own; top-level names stay (they are window globals).
 *   js/<entry>.js      main.js, motion.js and calendar-detail.js with the
 *                      modules they import bundled in, shared code in
 *                      js/chunks/ (content-hashed names, so immutable).
 *
 * The critical-CSS files under css/ are generated by build_critical_css.mjs
 * and only recorded here (this script keeps their manifest entries).
 */
import { build, transform, version as esbuildVersion } from "esbuild";
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const STATIC = path.join(ROOT, "static");
const MIN = path.join(STATIC, "min");
const JS_NAME = /^[\w.-]+\.js$/;
const ES_MODULE = /^(?:import|export)\s/m;
const JS_TARGET = "es2020";

// The cascade order of templates/index.html (tests/test_min_assets.py keeps the
// template's fallback <link> list equal to this one). Tailwind comes last so
// its utilities override the custom CSS.
export const CSS_ORDER = [
    "css/tokens.css",
    "style.css",
    "css/typography.css",
    "css/reader.css",
    "css/sidebar.css",
    "css/halacha.css",
    "css/prayer.css",
    "css/siddur.css",
    "css/ai.css",
    "css/conversation.css",
    "css/history.css",
    "css/calendar.css",
    "css/calendar-detail.css",
    "css/loading.css",
    "css/tailwind.css",
];
export const MODULE_ENTRIES = ["main.js", "motion.js", "calendar-detail.js"];

const sha256 = (data) => createHash("sha256").update(data).digest("hex");
// The manifest stores "sha256:<hex>", not bare hex: a bare 64-hex value beside a
// file name such as css/tokens.css or conversation-api.js reads as a leaked key to
// the secret scanner (gitleaks generic-api-key).
const tagged = (data) => `sha256:${sha256(data)}`;

function listJs() {
    return fs
        .readdirSync(path.join(STATIC, "js"))
        .filter((name) => JS_NAME.test(name))
        .sort();
}

function readStatic(rel) {
    return fs.readFileSync(path.join(STATIC, rel));
}

function warnings(label, list) {
    for (const w of list) {
        const where = w.location ? `${w.location.file || label}:${w.location.line}` : label;
        console.warn(`  warning (${where}): ${w.text}`);
    }
}

/** @returns {Promise<{files: Map<string, Buffer>, manifest: object}>} */
export async function compute(previousManifest = null) {
    const files = new Map();
    const manifest = {
        version: 1,
        esbuild: esbuildVersion,
        css: { sources: {}, sourcesHash: "", bundle: "css/app.css", critical: {} },
        js: { classic: {}, modules: { entries: {}, sources: {}, outputs: {} } },
    };

    // ── CSS ────────────────────────────────────────────────────────────────
    const parts = [];
    const plainSources = {};
    for (const rel of CSS_ORDER) {
        const data = readStatic(rel);
        manifest.css.sources[rel] = tagged(data);
        plainSources[rel] = sha256(data);
        parts.push(`/* ${rel} */\n${data.toString("utf8")}`);
    }
    // Over the bare digests, so it names the same stylesheets as it always has.
    manifest.css.sourcesHash = sha256(JSON.stringify(plainSources));
    const css = await transform(parts.join("\n"), {
        loader: "css",
        minify: true,
        charset: "utf8",
        legalComments: "none",
    });
    warnings("app.css", css.warnings);
    if (/<\/style/i.test(css.code)) throw new Error("app.css contains '</style' and could not be inlined");
    files.set("css/app.css", Buffer.from(css.code));
    // The critical-CSS entries belong to build_critical_css.mjs; carry them over.
    if (previousManifest?.css?.critical) manifest.css.critical = previousManifest.css.critical;

    // ── classic scripts and module graph inputs ────────────────────────────
    const classic = [];
    const modules = [];
    for (const name of listJs()) {
        const data = readStatic(`js/${name}`);
        (ES_MODULE.test(data.toString("utf8")) ? modules : classic).push([name, data]);
    }
    for (const [name, data] of classic) {
        const out = await transform(data.toString("utf8"), {
            loader: "js",
            minify: true,
            target: JS_TARGET,
            charset: "utf8",
            legalComments: "none",
        });
        warnings(name, out.warnings);
        files.set(`js/${name}`, Buffer.from(out.code));
        manifest.js.classic[name] = { source: tagged(data) };
    }
    for (const [name, data] of modules) manifest.js.modules.sources[name] = tagged(data);

    // ── module entries (bundled, shared code split into content-hashed chunks)
    const result = await build({
        entryPoints: MODULE_ENTRIES.map((name) => path.join(STATIC, "js", name)),
        outdir: path.join(MIN, "js"),
        entryNames: "[name]",
        chunkNames: "chunks/[name]-[hash]",
        bundle: true,
        splitting: true,
        format: "esm",
        minify: true,
        target: JS_TARGET,
        charset: "utf8",
        legalComments: "none",
        write: false,
        metafile: true,
        logLevel: "silent",
    });
    warnings("modules", result.warnings);
    for (const file of result.outputFiles) {
        const rel = path.relative(MIN, file.path).split(path.sep).join("/");
        files.set(rel, Buffer.from(file.contents));
    }
    for (const name of MODULE_ENTRIES) manifest.js.modules.entries[name] = `js/${name}`;
    for (const [rel, data] of files) {
        if (rel.startsWith("js/")) manifest.js.modules.outputs[rel] = sha256(data).slice(0, 12);
    }
    // An unminified input that is no module of the bundle graph would be a
    // module nothing loads; list those that are loaded by none of the entries.
    const reached = new Set();
    for (const out of Object.values(result.metafile.outputs)) {
        for (const input of Object.keys(out.inputs)) reached.add(path.basename(input));
    }
    manifest.js.modules.unreached = modules.map(([name]) => name).filter((name) => !reached.has(name));

    manifest.js.modules.outputs = Object.fromEntries(
        Object.entries(manifest.js.modules.outputs).sort(([a], [b]) => Number(a > b) - Number(a < b)),
    );
    return { files, manifest };
}

function serialize(manifest) {
    return `${JSON.stringify(manifest, null, 2)}\n`;
}

function readPreviousManifest() {
    try {
        return JSON.parse(fs.readFileSync(path.join(MIN, "manifest.json"), "utf8"));
    } catch {
        return null;
    }
}

/** Files this script owns under static/min/ (never the critical CSS). */
function ownedFiles(manifest) {
    const owned = new Set(["manifest.json", manifest.css.bundle]);
    for (const rel of Object.keys(manifest.js.modules.outputs)) owned.add(rel);
    for (const name of Object.keys(manifest.js.classic)) owned.add(`js/${name}`);
    return owned;
}

async function main() {
    const checkOnly = process.argv.includes("--check");
    const previous = readPreviousManifest();
    const { files, manifest } = await compute(previous);
    const text = serialize(manifest);

    if (checkOnly) {
        const stale = [];
        const expected = ownedFiles(manifest);
        for (const [rel, data] of files) {
            const target = path.join(MIN, rel);
            if (!fs.existsSync(target) || !fs.readFileSync(target).equals(data)) stale.push(rel);
        }
        if (!fs.existsSync(path.join(MIN, "manifest.json")) || fs.readFileSync(path.join(MIN, "manifest.json"), "utf8") !== text) {
            stale.push("manifest.json");
        }
        const present = [];
        const walk = (dir) => {
            for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
                const full = path.join(dir, entry.name);
                if (entry.isDirectory()) walk(full);
                else present.push(path.relative(MIN, full).split(path.sep).join("/"));
            }
        };
        if (fs.existsSync(MIN)) walk(MIN);
        // critical-*.css belong to build_critical_css.mjs, not to this script.
        const extra = present.filter((rel) => !expected.has(rel) && !/^css\/critical-[\w-]+\.css$/.test(rel));
        if (stale.length || extra.length) {
            console.error("static/min/ does not match the sources. Run: npm run build:assets");
            for (const rel of stale) console.error(`  stale or missing: ${rel}`);
            for (const rel of extra) console.error(`  not produced by the build: ${rel}`);
            process.exit(1);
        }
        console.log(`static/min/ is up to date (${files.size} files).`);
        return;
    }

    const owned = ownedFiles(manifest);
    for (const [rel, data] of files) {
        const target = path.join(MIN, rel);
        fs.mkdirSync(path.dirname(target), { recursive: true });
        if (!fs.existsSync(target) || !fs.readFileSync(target).equals(data)) fs.writeFileSync(target, data);
    }
    fs.writeFileSync(path.join(MIN, "manifest.json"), text);
    // Chunks are named by content: a rebuilt one leaves its old file behind.
    // Remove only files the previous manifest listed that this build no longer produces.
    if (previous) {
        for (const rel of ownedFiles(previous)) {
            if (!owned.has(rel)) fs.rmSync(path.join(MIN, rel), { force: true });
        }
    }
    const total = [...files.values()].reduce((sum, data) => sum + data.length, 0);
    console.log(`static/min/: ${files.size} files, ${(total / 1024).toFixed(0)} KB (css ${(files.get("css/app.css").length / 1024).toFixed(0)} KB)`);
    if (manifest.js.modules.unreached.length) {
        console.log(`  modules no entry imports: ${manifest.js.modules.unreached.join(", ")}`);
    }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    main().catch((err) => {
        console.error(err);
        process.exit(1);
    });
}
